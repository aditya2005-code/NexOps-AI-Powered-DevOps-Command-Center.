import uuid
from datetime import datetime
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field


class RemediationEligibilityStatus(str, Enum):
    ELIGIBLE = "eligible"
    INSUFFICIENT_EVIDENCE = "insufficient_evidence"
    NO_CODE_CHANGE_REQUIRED = "no_code_change_required"
    CONFIGURATION_ISSUE = "configuration_issue"
    INFRASTRUCTURE_ISSUE = "infrastructure_issue"
    UNSUPPORTED_REMEDIATION = "unsupported_remediation"


class RemediationEligibility(BaseModel):
    status: RemediationEligibilityStatus
    reason: str
    recommended_action: Optional[str] = None
    eligible_files: List[str] = Field(default_factory=list)

    model_config = ConfigDict(from_attributes=True)


class RemediationPlan(BaseModel):
    incident_id: str
    investigation_execution_id: Optional[str] = None
    selected_hypothesis: str
    supporting_evidence_ids: List[str] = Field(default_factory=list)
    proposed_remediation: str
    expected_behavior_change: str
    files_affected: List[str] = Field(default_factory=list)
    technical_rationale: str
    risks: List[str] = Field(default_factory=list)
    assumptions: List[str] = Field(default_factory=list)
    verification_requirements: List[str] = Field(default_factory=list)

    model_config = ConfigDict(from_attributes=True)


class PatchRiskLevel(str, Enum):
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class PatchRiskAssessment(BaseModel):
    risk_level: PatchRiskLevel
    risk_score: float = Field(..., ge=0.0, le=1.0)
    risk_factors: List[str] = Field(default_factory=list)
    potential_side_effects: List[str] = Field(default_factory=list)
    rollback_complexity: str = Field(default="LOW")

    model_config = ConfigDict(from_attributes=True)


class ProposedPatch(BaseModel):
    """Structured patch generated by the LLM."""
    title: str = Field(..., max_length=255, description="Short summary of the bug fix")
    problem_description: str = Field(..., description="Explanation of the code defect addressed")
    technical_rationale: str = Field(..., description="Why this specific change resolves the problem")
    files_affected: List[str] = Field(..., description="List of file paths modified in the patch")
    diff_content: str = Field(..., description="Standard unified Git diff formatted content")
    supporting_evidence_ids: List[str] = Field(
        default_factory=list, description="Evidence IDs from investigation that substantiate this change"
    )
    expected_outcome: str = Field(..., description="Expected runtime behavior post-fix")
    potential_side_effects: List[str] = Field(
        default_factory=list, description="Possible collateral impacts or edge cases"
    )
    verification_steps: List[str] = Field(
        default_factory=list, description="Commands or test steps to verify the fix"
    )
    risk_level: PatchRiskLevel = Field(default=PatchRiskLevel.LOW)

    model_config = ConfigDict(from_attributes=True)


class PatchValidationResult(BaseModel):
    is_valid: bool
    syntax_valid: bool
    authorized_files_only: bool
    lines_added: int = 0
    lines_removed: int = 0
    validation_errors: List[str] = Field(default_factory=list)

    model_config = ConfigDict(from_attributes=True)


class RemediationResponse(BaseModel):
    """API response model for an incident remediation execution."""
    incident_id: uuid.UUID
    execution_id: uuid.UUID
    patch_id: Optional[uuid.UUID] = None
    patch_hash: Optional[str] = None
    eligibility: RemediationEligibility
    remediation_plan: Optional[RemediationPlan] = None
    proposed_patch: Optional[ProposedPatch] = None
    validation: Optional[PatchValidationResult] = None
    risk: Optional[PatchRiskAssessment] = None
    execution_status: str
    duration_seconds: float
    created_at: datetime

    model_config = ConfigDict(from_attributes=True)

